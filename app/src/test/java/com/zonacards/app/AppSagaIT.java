/**
 * The application as it is deployed by default: one process that serves every module
 * ({@code ZC_MODULES=lotes,giftcards}). Nobody plays the other side here. A lote requested
 * through the API of one module is generated by the other and comes back generated, and the only
 * thing that travels between them is events: outbox, SNS, SQS, inbox.
 *
 * <p>The other two test profiles run the same application serving one module each. Together
 * they are the claim of the architecture: the same code behaves the same whether two modules
 * share a process or not.
 */
@QuarkusTest
@TestProfile(AppTestResource.EveryModule.class)
class AppSagaIT {

  private static final String LOTES = "/api/v1/lotes";
  private static final String GIFTCARDS = "/api/v1/giftcards";
  private static final Duration EVENTUALLY = Duration.ofSeconds(60);

  static TestTokens tokens;
  static FlociFixture floci;
  static String workUrl;

  @Inject UnitOfWork uow;

  // Looked up, not injected directly: this class is also part of the application when it runs
  // with one module, and there the other module's datasource is inactive.
  @Inject
  @DataSource("lotes")
  InjectableInstance<AgroalDataSource> lotesDb;

  @Inject
  @DataSource("giftcards")
  InjectableInstance<AgroalDataSource> giftcardsDb;

  @BeforeAll
  static void connect() {
    Config config = ConfigProvider.getConfig();
    tokens = TestTokens.ofPrivateKey(config.getValue(TestConfig.JWT_PRIVATE_KEY, String.class));
    floci = FlociFixture.attach(URI.create(config.getValue(TestConfig.AWS_ENDPOINT, String.class)));
    workUrl = config.getValue(AppTestResource.WORK_URL, String.class);
  }

  private static RequestSpecification ana() {
    return given()
        .auth()
        .oauth2(tokens.user("pe", "ana", "lotes:read", "lotes:write", "lotes:anular", "giftcards:read"))
        .contentType(ContentType.JSON);
  }

  private static Map<String, Object> solicitud(int cantidad) {
    Map<String, Object> body = new HashMap<>();
    body.put("descripcion", "Campaña de fin de año");
    body.put("pais", "604");
    body.put("moneda", "PEN");
    body.put("monto", 50.00);
    body.put("cantidad", cantidad);
    body.put("vigenciaHasta", "2027-12-31");
    return body;
  }

  private static int giftcards(String query) {
    return ana().get(GIFTCARDS + query).then().statusCode(200).extract().path("page.total");
  }

  // --- the saga, with nobody playing a part ----------------------------------------------------

  @Test
  void aLoteIsGeneratedAndAnnulledAcrossTheTwoModules() {
    String lote =
        ana()
            .header("Idempotency-Key", UUID.randomUUID().toString())
            .body(solicitud(250))
            .post(LOTES)
            .then()
            .statusCode(201)
            .body("estado", equalTo("SOLICITADO"))
            .extract()
            .path("id");

    // lotes published the request; giftcards planned it, generated three fragments from its
    // work queue and reported each one; lotes counted them.
    await()
        .atMost(EVENTUALLY)
        .untilAsserted(
            () ->
                ana()
                    .get(LOTES + "/" + lote)
                    .then()
                    .statusCode(200)
                    .body("estado", equalTo("GENERADO"))
                    .body("progreso.fragmentosTotales", equalTo(3))
                    .body("progreso.fragmentosCompletados", equalTo(3))
                    .body("progreso.generadas", equalTo(250)));
    assertEquals(250, giftcards("?loteId=" + lote));
    assertEquals(250, giftcards("?loteId=" + lote + "&estado=GENERADA"));
    assertEquals(0, floci.depth(workUrl), "the work queue was drained");

    // The way back: annulled in lotes, applied in giftcards, confirmed to lotes.
    ana().delete(LOTES + "/" + lote + "?motivo=Campaña cancelada").then().statusCode(200).body("estado", equalTo("ANULADO"));
    await()
        .atMost(EVENTUALLY)
        .untilAsserted(
            () ->
                ana()
                    .get(LOTES + "/" + lote)
                    .then()
                    .body("anulacionAplicadaEn", notNullValue())
                    .body("giftcardsAnuladas", equalTo(250)));
    assertEquals(250, giftcards("?loteId=" + lote + "&estado=ANULADA"));
    assertEquals(0, giftcards("?loteId=" + lote + "&estado=GENERADA"));
  }

  // --- one process, still two modules ----------------------------------------------------------

  @Test
  void everyModuleReportsItsOwnLoopsAndItsOwnMetrics() {
    given()
        .get("/q/health")
        .then()
        .statusCode(200)
        .body("status", equalTo("UP"))
        .body("checks.find { it.name == 'eventx-loops' }.data.'lotes/outbox-relay'", equalTo("alive"))
        .body("checks.find { it.name == 'eventx-loops' }.data.'lotes/consumer-lotes-inbox'", equalTo("alive"))
        .body("checks.find { it.name == 'eventx-loops' }.data.'giftcards/outbox-relay'", equalTo("alive"))
        .body("checks.find { it.name == 'eventx-loops' }.data.'giftcards/consumer-giftcards-inbox'", equalTo("alive"))
        .body("checks.find { it.name == 'eventx-loops' }.data.'giftcards/consumer-giftcards-generacion'", equalTo("alive"))
        .body("checks.find { it.name == 'Database connections health check' }.data.lotes", equalTo("UP"))
        .body("checks.find { it.name == 'Database connections health check' }.data.giftcards", equalTo("UP"));
    // Two outboxes in one process: without the tag one gauge would overwrite the other.
    given()
        .get("/q/metrics")
        .then()
        .statusCode(200)
        .body(containsString("zonacards_outbox_pending{module=\"lotes\"}"))
        .body(containsString("zonacards_outbox_pending{module=\"giftcards\"}"))
        .body(containsString("zonacards_outbox_oldest_pending_seconds{module=\"lotes\"}"))
        .body(containsString("zonacards_outbox_oldest_pending_seconds{module=\"giftcards\"}"));
  }

  @Test
  void sharingAProcessDoesNotShareTheDatabase() throws SQLException {
    AgroalDataSource lotes = lotesDb.get();
    AgroalDataSource giftcards = giftcardsDb.get();

    // Each module connects with its own role, which sees only its own schema.
    assertEquals("lotes_app", uow.inTx(() -> scalar(lotes, "select current_user")));
    assertEquals("giftcards_app", uow.inTx(() -> scalar(giftcards, "select current_user")));
    assertEquals("42501", sqlState(() -> uow.inTx(() -> scalar(lotes, "select count(*) from giftcards.giftcard"))));
    assertEquals("42501", sqlState(() -> uow.inTx(() -> scalar(giftcards, "select count(*) from lotes.lote"))));

    // And a unit of work cannot span two modules: the transaction refuses the second datasource.
    // There is no way to write "update my table and yours" that commits; what remains is an event.
    IllegalStateException spanning =
        assertThrows(
            IllegalStateException.class,
            () ->
                uow.runInTx(
                    () -> {
                      scalar(lotes, "select count(*) from lote");
                      scalar(giftcards, "select count(*) from giftcard");
                    }));
    // The second connection is the one that is refused, when it tries to join the transaction.
    assertTrue(spanning.getCause() instanceof SQLException, String.valueOf(spanning.getCause()));
    assertTrue(spanning.getCause().getMessage().contains("existing transaction"), spanning.getCause().getMessage());
    // Each module on its own keeps working afterwards.
    assertEquals("lotes_app", uow.inTx(() -> scalar(lotes, "select current_user")));
    assertEquals("giftcards_app", uow.inTx(() -> scalar(giftcards, "select current_user")));
  }

  private static String scalar(AgroalDataSource dataSource, String sql) {
    try (Connection connection = dataSource.getConnection();
        Statement statement = connection.createStatement();
        ResultSet rows = statement.executeQuery(sql)) {
      rows.next();
      return rows.getString(1);
    } catch (SQLException e) {
      throw new IllegalStateException(e);
    }
  }

  private static String sqlState(Runnable work) {
    IllegalStateException failure = assertThrows(IllegalStateException.class, work::run);
    return ((SQLException) failure.getCause()).getSQLState();
  }
}
