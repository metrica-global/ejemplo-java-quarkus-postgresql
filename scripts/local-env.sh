#!/usr/bin/env bash
# Creates .env with the two keys the local giftcards service needs, if it does not exist yet.
# They are random and stay on this machine: .env is ignored by git. In AWS the equivalent keys
# are generated straight into Secrets Manager by Terraform.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT/.env"

if [ -f "$ENV_FILE" ] && grep -q '^ZC_GIFTCARDS_CODIGO_KEY=' "$ENV_FILE" && grep -q '^ZC_GIFTCARDS_CODIGO_HMAC_KEY=' "$ENV_FILE"; then
  exit 0
fi

key() { head -c 32 /dev/urandom | base64 | tr -d '\n'; }

{
  echo "# Generated by scripts/local-env.sh for the local environment. Not a production secret."
  echo "# Deleting this file while the database volume exists makes stored card codes unreadable:"
  echo "# delete both together (make down)."
  echo "ZC_GIFTCARDS_CODIGO_KEY=$(key)"
  echo "ZC_GIFTCARDS_CODIGO_HMAC_KEY=$(key)"
} >> "$ENV_FILE"
chmod 600 "$ENV_FILE"
echo "created $ENV_FILE"
