#!/usr/bin/env bash
# The topology of the local system: which deployment serves each module.
#
# There is one application image. By default one service, the nucleo, serves every module.
# PROMOTING a module gives it its own service, which can then be scaled by itself. Nothing is
# built and no image changes: only configuration (ZC_MODULES, the number of replicas and the
# route in the gateway). It is the local version of what the Terraform variable
# `promoted_modules` does in AWS, in the same two stages, so that the module is never without
# someone serving it:
#
#   expandir   the module's own service starts, with the image that is already running. The
#              nucleo keeps serving the module and keeps receiving its traffic. Both consume
#              the same queues for a while; nothing is lost or duplicated.
#   contraer   the traffic moves to the own service, and the nucleo is redeployed without the
#              module (same image, new ZC_MODULES).
#
# REINTEGRATING is the way back: the nucleo is redeployed serving the module again, then the
# traffic returns to it and the own service is removed.
#
#   scripts/topologia.sh estado
#   scripts/topologia.sh promover   giftcards [expandir|contraer]
#   scripts/topologia.sh reintegrar giftcards [expandir|contraer]
#   scripts/topologia.sh rutas          write the gateway's routes from .env (used by make up)
#   scripts/topologia.sh restablecer    forget the topology: next `make up` starts from the default
#
# ZC_REPLICAS_PROPIAS=2   replicas the own service starts with
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cd "$ROOT"

RUTAS_DIR="$ROOT/deploy/local/.state/gateway"
REPLICAS_PROPIAS="${ZC_REPLICAS_PROPIAS:-2}"

titulo() { printf '\033[1m%s\033[0m\n' "$*"; }
paso() { printf '  → %s\n' "$*"; }

# --- gateway -----------------------------------------------------------------------------------

# One rule per module, like the listener rules of the load balancer.
escribir_rutas() {
  local tmp modulo
  mkdir -p "$RUTAS_DIR"
  tmp="$(mktemp "$RUTAS_DIR/.routes.XXXXXX")"
  {
    echo "# Generated by scripts/topologia.sh from the topology in .env. Do not edit."
    for modulo in "${MODULOS[@]}"; do
      echo "location /api/v1/$modulo { set \$upstream http://$(ruta_de "$modulo"):8080; proxy_pass \$upstream; }"
    done
  } >"$tmp"
  chmod 644 "$tmp"
  mv "$tmp" "$RUTAS_DIR/routes.conf"
}

# nginx -s reload starts new workers with the new routes and lets the old ones finish the
# requests they have: the entry point is not replaced and no connection is dropped.
recargar_gateway() {
  [ -n "$(contenedores gateway)" ] || return 0
  docker compose exec -T gateway nginx -t >/dev/null 2>&1 || morir "las rutas generadas no son válidas para el gateway"
  docker compose exec -T gateway nginx -s reload >/dev/null 2>&1
}

mover_trafico() { # module destination-service
  env_fijar "ZC_RUTA_${1^^}" "$2"
  escribir_rutas
  recargar_gateway
  paso "el gateway envía /api/v1/$1 a '$2' (recargado, sin reiniciarlo)"
}

# --- deployments -------------------------------------------------------------------------------

# A rolling deployment, the way ECS does it (minimum healthy 100 %, maximum 200 %): the new
# replicas start with the new configuration; only when they are healthy are the old ones asked
# to stop, and those finish the work they have in hand before they exit.
redesplegar() { # service
  local servicio="$1" viejos cantidad
  viejos="$(contenedores "$servicio")"
  cantidad="$(wc -w <<<"$viejos" | tr -d ' ')"
  [ "$cantidad" -gt 0 ] || morir "$servicio no tiene réplicas en ejecución; ejecute: make up"
  escalar "$servicio" $((cantidad * 2))
  paso "$cantidad réplicas nuevas de '$servicio' sanas con ZC_MODULES=$(modulos_nucleo); se retiran las $cantidad anteriores"
  # shellcheck disable=SC2086
  docker stop -t 90 $viejos >/dev/null
  # shellcheck disable=SC2086
  docker rm $viejos >/dev/null
  [ "$(replicas_sanas "$servicio")" = "$cantidad" ] || morir "'$servicio' no quedó con $cantidad réplicas sanas"
}

misma_imagen() {
  local ids
  ids="$(imagenes "${SERVICIOS_APP[@]}")"
  [ "$(grep -c . <<<"$ids")" = 1 ] || morir "los contenedores de la aplicación no corren la misma imagen: $ids"
  paso "núcleo y servicios propios corren la misma imagen (${ids:7:12}): no se construyó nada"
}

# --- validation --------------------------------------------------------------------------------

modulo_valido() {
  local modulo="${1:-}" m
  [ -n "$modulo" ] || morir "falta el módulo. Ejemplo: make promover MODULO=giftcards"
  for m in "${MODULOS[@]}"; do
    [ "$m" != "$modulo" ] || break
  done
  [ "$m" = "$modulo" ] || morir "'$modulo' no es un módulo de la aplicación (módulos: ${MODULOS[*]})"
  # In AWS any module of the catalog can be promoted: Terraform creates its service from the
  # list. docker compose cannot create services from a list, so the local system declares the
  # own service of one module.
  docker compose config --services | grep -qx "$modulo" ||
    morir "el sistema local solo define el servicio propio de giftcards (docker-compose.yml); en AWS '$modulo' se promueve igual, agregándolo a promoted_modules"
  [ -n "$(contenedores nucleo)" ] || morir "el sistema local no está en ejecución; ejecute: make up"
}

sin() { # list element  ->  the comma-separated list without the element
  local resto=() actuales m
  IFS=, read -ra actuales <<<"$1"
  for m in "${actuales[@]}"; do [ "$m" = "$2" ] || resto+=("$m"); done
  (IFS=,; echo "${resto[*]}")
}

con() { # element  ->  the modules of the nucleo plus the element, in the order of the application
  local resultado=() m
  for m in "${MODULOS[@]}"; do
    if en_nucleo "$m" || [ "$m" = "$1" ]; then resultado+=("$m"); fi
  done
  (IFS=,; echo "${resultado[*]}")
}

# --- commands ----------------------------------------------------------------------------------

estado() {
  local modulo
  titulo "Topología local"
  printf '  %-10s %s réplicas, atiende: %s\n' nucleo "$(replicas nucleo)" "$(modulos_nucleo)"
  for modulo in "${MODULOS[@]}"; do
    docker compose config --services 2>/dev/null | grep -qx "$modulo" || continue
    if [ "$(replicas "$modulo")" = 0 ]; then
      printf '  %-10s sin réplicas (el módulo no está promovido)\n' "$modulo"
    else
      printf '  %-10s %s réplicas, atiende: %s\n' "$modulo" "$(replicas "$modulo")" "$modulo"
    fi
  done
  for modulo in "${MODULOS[@]}"; do
    printf '  %-10s /api/v1/%s → %s\n' ruta "$modulo" "$(ruta_de "$modulo")"
  done
}

promover() { # module [stage]
  local modulo="$1" etapa="${2:-todo}"
  modulo_valido "$modulo"
  case "$etapa" in todo | expandir | contraer) ;; *) morir "etapa desconocida: $etapa (expandir o contraer)" ;; esac

  if [ "$etapa" != contraer ]; then
    en_nucleo "$modulo" && [ "$(replicas "$modulo")" = 0 ] ||
      morir "'$modulo' no está solo en el núcleo (make topologia); no hay nada que expandir"
    [ -n "$(sin "$(modulos_nucleo)" "$modulo")" ] || morir "el núcleo no puede quedarse sin módulos"
    titulo "Expandir: '$modulo' arranca como servicio propio; el núcleo lo sigue atendiendo"
    env_fijar "ZC_${modulo^^}_REPLICAS" "$REPLICAS_PROPIAS"
    escalar "$modulo" "$REPLICAS_PROPIAS"
    paso "servicio '$modulo' con $REPLICAS_PROPIAS réplicas sanas y ZC_MODULES=$modulo"
    misma_imagen
    paso "el tráfico de /api/v1/$modulo sigue en '$(ruta_de "$modulo")'; núcleo y '$modulo' consumen las mismas colas"
  fi

  if [ "$etapa" != expandir ]; then
    en_nucleo "$modulo" && [ "$(replicas_sanas "$modulo")" -ge 1 ] ||
      morir "'$modulo' no está expandido (make topologia); ejecute antes la etapa expandir"
    titulo "Contraer: el tráfico pasa al servicio propio y el núcleo deja '$modulo'"
    mover_trafico "$modulo" "$modulo"
    env_fijar ZC_NUCLEO_MODULES "$(sin "$(modulos_nucleo)" "$modulo")"
    redesplegar nucleo
    misma_imagen
    titulo "'$modulo' es ahora un servicio propio. Se escala solo: docker compose up -d --no-deps --no-recreate --scale $modulo=4 $modulo"
  fi
}

reintegrar() { # module [stage]
  local modulo="$1" etapa="${2:-todo}"
  modulo_valido "$modulo"
  case "$etapa" in todo | expandir | contraer) ;; *) morir "etapa desconocida: $etapa (expandir o contraer)" ;; esac

  if [ "$etapa" != contraer ]; then
    promovido "$modulo" || morir "'$modulo' no está promovido (make topologia); no hay nada que reintegrar"
    titulo "Expandir: el núcleo vuelve a atender '$modulo'; el servicio propio sigue en pie"
    env_fijar ZC_NUCLEO_MODULES "$(con "$modulo")"
    redesplegar nucleo
    paso "el tráfico de /api/v1/$modulo sigue en '$(ruta_de "$modulo")'; núcleo y '$modulo' consumen las mismas colas"
  fi

  if [ "$etapa" != expandir ]; then
    en_nucleo "$modulo" && [ "$(ruta_de "$modulo")" = "$modulo" ] ||
      morir "el núcleo todavía no atiende '$modulo' (make topologia); ejecute antes la etapa expandir"
    titulo "Contraer: el tráfico vuelve al núcleo y el servicio propio se retira"
    mover_trafico "$modulo" nucleo
    env_fijar "ZC_${modulo^^}_REPLICAS" 0
    escalar "$modulo" 0
    paso "servicio '$modulo' sin réplicas (terminaron su trabajo antes de salir)"
    titulo "'$modulo' vuelve a vivir en el núcleo."
  fi
}

restablecer() {
  [ -f "$ENV_FILE" ] || return 0
  local tmp
  tmp="$(mktemp "$ENV_FILE.XXXXXX")"
  grep -vE '^ZC_(NUCLEO_MODULES|[A-Z]+_REPLICAS|RUTA_[A-Z]+)=' "$ENV_FILE" >"$tmp" || true
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
  escribir_rutas
}

case "${1:-estado}" in
  estado) estado ;;
  promover) promover "${2:-}" "${3:-todo}" && estado ;;
  reintegrar) reintegrar "${2:-}" "${3:-todo}" && estado ;;
  rutas) escribir_rutas ;;
  restablecer) restablecer ;;
  *) morir "uso: scripts/topologia.sh estado | promover MODULO [expandir|contraer] | reintegrar MODULO [expandir|contraer] | rutas | restablecer" ;;
esac
